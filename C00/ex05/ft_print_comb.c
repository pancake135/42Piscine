#include <unistd.h>

void	ft_print_comb(void)
{
	char	a;
	char	b;
	char	c;

	c = '0';
	while (c <= '7')
	{
		b = c + 1;
		while (b <= '8')
		{
			a = b + 1;
			while (a <= '9')
			{
				write(1, &c, 1);
				write(1, &b, 1);
				write(1, &a, 1);
				if (!(c == '7' && b == '8' && a == '9'))
					write(1, ", ", 2);
				a++;
			}
			b++;
		}
		c++;
	}
}
